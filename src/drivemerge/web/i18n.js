const DICTS = { 'zh-TW': zh, en };
export const LANGS = Object.keys(DICTS);
export const dictionaries = DICTS;

function storedLang() {
  try {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q && DICTS[q]) return q;
    const s = window.localStorage.getItem('dm-lang');
    if (s && DICTS[s]) return s;
  } catch (e) { /* storage blocked: use the default */ }
  return 'zh-TW';
}

let current = storedLang();

export const getLang = () => current;
export function setLang(lang) {
  if (!DICTS[lang]) return;
  current = lang;
  try { window.localStorage.setItem('dm-lang', lang); } catch (e) { /* not persisted */ }
}

/** "one|other": the first form when vars.n is 1, the last otherwise. Chinese strings have no "|". */
function plural(raw, vars) {
  if (!raw.includes('|') || !vars || vars.n === undefined) return raw;
  const forms = raw.split('|');
  return Number(String(vars.n).replace(/,/g, '')) === 1 ? forms[0] : forms[forms.length - 1];
}

/** t(key, {n: 3}, fallback): the current language, then English, then `fallback` (or the key itself). */
export function t(key, vars, fallback) {
  const raw = DICTS[current][key] !== undefined ? DICTS[current][key] : en[key];
  if (raw === undefined) return fallback !== undefined ? fallback : key;
  if (!vars) return raw;
  return plural(raw, vars).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}
